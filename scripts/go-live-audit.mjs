import {readFileSync,existsSync} from 'node:fs';
import assert from 'node:assert/strict';
const file=(p)=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const requireFile=(p)=>assert.ok(existsSync(new URL('../'+p,import.meta.url)),p+' fehlt');
for(const path of ['app/agb/page.tsx','app/datenschutz/page.tsx','app/widerruf/page.tsx','app/widerruf-online/page.tsx','app/api/widerruf/route.ts','app/impressum/page.tsx','app/versand/page.tsx','app/api/checkout/route.ts','app/api/stripe/webhook/route.ts','app/admin/bestellungen/page.tsx'])requireFile(path);
const checkout=file('app/api/checkout/route.ts');
const cart=file('app/warenkorb/page.tsx');
const webhook=file('app/api/stripe/webhook/route.ts');
const layout=file('app/layout.tsx');
const shipping=file('app/versand/page.tsx');
const withdraw=file('app/widerruf-online/page.tsx');
assert.match(checkout,/country\s*!==\s*'DE'/,'Checkout muss ausschließlich DE akzeptieren');
assert.match(checkout,/return_url/,'Checkout-Rücksprungadresse fehlt');
assert.match(checkout,/PAYMENTS_LIVE_APPROVED/,'Live-Gate fehlt');
assert.match(checkout,/rk_live_/,'Restricted-Live-Key im Checkout nicht unterstützt');
assert.match(webhook,/rk_live_/,'Restricted-Live-Key im Webhook nicht unterstützt');
assert.match(file('app/bestellung/page.tsx'),/rk_live_/,'Restricted-Live-Key auf Bestellseite nicht unterstützt');
assert.match(webhook,/timingSafeEqual/,'Stripe-Signaturprüfung fehlt');
assert.match(webhook,/PAYMENTS_LIVE_APPROVED/,'Webhook-Live-Gate fehlt');
assert.match(webhook,/savePaidOrder/,'Bestellspeicherung fehlt');
assert.match(withdraw,/Widerruf bestätigen/,'Widerrufsbestätigung fehlt');
assert.match(layout,/widerruf-online/,'Widerrufslink im Footer fehlt');
assert.match(layout,/\/agb/,'AGB-Link fehlt');
assert.match(shipping,/2–4 Werktage/,'Lieferfrist fehlt');
assert.match(shipping,/9,90 €/,'Versandkosten fehlen');
assert.doesNotMatch(cart,/<option value="AT">/,'AT-Auswahl muss entfernt sein');
const products=JSON.parse(file('products.json'));
assert.ok(Array.isArray(products)&&products.length>800,'Ajax-Katalog scheint unvollständig');
assert.ok(products.every(p=>p.sku&&p.name&&Number.isInteger(p.priceCents)&&p.priceCents>=0),'Katalog enthält ungültige Stammdaten');
assert.ok(products.filter(p=>p.priceCents>0).length>850,'Zu wenige regulär bepreiste Produkte');
assert.match(file('app/shop/page.tsx'),/priceCents>0/,'Nullpreis-Artikel müssen im Shop ausgeblendet werden');
console.log('Statische Go-live-Prüfung bestanden: DE-Checkout, Stripe-Gates, Widerruf, Rechtstexte, Katalog');
console.log('ACHTUNG: Rechtliche Endabnahme, GPSR-Herstellerdaten, Lagerverfügbarkeit, Steuer-/Mailprüfung und echte Zahlung werden hier NICHT simuliert.');
